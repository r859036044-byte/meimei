    AudioStreamPlayer _dailyVoice;
    void StopDailyVoice() { _voiceQueue?.Clear(); _dailyVoice?.Stop(); }
    readonly Queue<AudioStream> _voiceQueue = new();

    static AudioStream LoadDailyVoiceClip(string clipId)
    {
        string resPath = "res://Resources/Audio/Voice/RJ01047725/" + clipId.Trim() + ".wav";
        if (ResourceLoader.Exists(resPath))
        {
            var st = GD.Load<AudioStream>(resPath);
            if (st != null) return st;
        }
        string absPath = ProjectSettings.GlobalizePath(resPath);
        if (System.IO.File.Exists(absPath))
        {
            return AudioStreamWav.LoadFromFile(absPath);
        }
        return null;
    }

    void PlayDailyVoice(string speaker, string text)
    {
        StopDailyVoice();
        _voiceQueue.Clear();
        if (IsFast || (speaker != "莉奈" && speaker != "小莉奈" && !(string.IsNullOrEmpty(speaker) && text != null && NarrationVoiceTexts.Contains(text))) || text == null || !DailyVoiceLines.TryGetValue(text, out var clips)) return;
        if (speaker == "小莉奈" && ChildVoiceMuted.Contains(text)) return;
        if ((speaker == "莉奈" || speaker == "小莉奈") && AfterMemoryVoiceMuted.Contains(text)) return;
        bool child = speaker == "小莉奈" && ChildVoiceTexts.Contains(text);
        foreach (var clip in clips.Split(','))
        {
            if (BreathyClips.Contains(clip.Trim())) continue;
            var st = (child ? LoadDailyVoiceClip("child_" + clip.Trim()) : null) ?? LoadDailyVoiceClip(clip);
            if (st != null) _voiceQueue.Enqueue(st);
        }
        if (_voiceQueue.Count == 0) return;
        if (_dailyVoice == null)
        {
            _dailyVoice = new AudioStreamPlayer { Name = "DailyDialogueVoice", MaxPolyphony = 1 };
            AddChild(_dailyVoice);
            _dailyVoice.Finished += PlayNextVoice;
        }
        PlayNextVoice();
    }
    void PlayNextVoice()
    {
        if (_dailyVoice == null || _voiceQueue.Count == 0) return;
        _dailyVoice.VolumeLinear = SettingsManager.Instance?.VoiceVolume ?? 1f;
        _dailyVoice.StreamPaused = false;
        _dailyVoice.Stream = _voiceQueue.Dequeue();
        _dailyVoice.Play();
    }
    // 語音提前播放：台詞一開始處理就播，不等鏡頭/淡入動畫跑完才開始打字
    bool _voicePre;
    string _voicePreText;
    public void PreplayVoice(string speaker, string text)
    {
        PlayDailyVoice(speaker, text);
        _voicePre = true;
        _voicePreText = text;
    }
    void UpdateDailyVoice()
    {
        if (_dailyVoice == null) return;
        // 提前播放期間對話框可能還沒顯示，不能因此把語音停掉
        if (IsFast || !IsInstanceValid(_box) || (!_voicePre && !_box.IsVisibleInTree())) { StopDailyVoice(); _voicePre = false; return; }
        _dailyVoice.VolumeLinear = SettingsManager.Instance?.VoiceVolume ?? 1f;
        _dailyVoice.StreamPaused = Paused;
    }
